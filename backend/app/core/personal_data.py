"""Личные данные, которые бот не заполняет никогда (§19).

Это правило кодом, а не промптом: промпт можно случайно переписать,
а поле паспорта заполнять нельзя ни при каких настройках.
"""

import re

FORBIDDEN_PATTERNS: tuple[tuple[str, str], ...] = (
    (r"паспорт", "номер паспорта"),
    (r"удостоверени[ея]\s*личност", "удостоверение личности"),
    (r"\bиин\b|индивидуальн\w*\s+идентификационн", "ИИН"),
    (r"\bснилс\b", "СНИЛС"),
    (r"\bинн\b", "ИНН"),
    (r"адрес\s+прожива|домашний\s+адрес|адрес\s+регистрац|прописк", "адрес проживания"),
    (
        r"банковск\w*\s+реквизит|номер\s+карты|номер\s+счёта|номер\s+счета|\biban\b",
        "банковские реквизиты",
    ),
    (r"фото\s+с\s+документ|скан\s+документ|скан\s+удостоверени|селфи\s+с", "фото документа"),
    (r"данные\s+родственник|сведения\s+о\s+родственник", "данные родственников"),
    (r"дата\s+рождения\s+полност|полная\s+дата\s+рождения", "полная дата рождения"),
    (r"водительск\w*\s+удостоверени", "водительское удостоверение"),
    (r"номер\s+военного\s+билета|военный\s+билет", "военный билет"),
)

# Что подставлять из резюме можно
ALLOWED_FIELDS = ("телефон", "email", "почта", "город", "github", "портфолио", "ссылка")


def find_personal_data_request(text: str) -> str | None:
    """Вернуть название запрошенного личного поля или None.

    Совпадение означает статус NEEDS_USER_ACTION: отклик не отправляется,
    вакансия остаётся для ручной обработки.
    """
    lowered = text.lower().replace("ё", "е")
    for pattern, label in FORBIDDEN_PATTERNS:
        if re.search(pattern.replace("ё", "е"), lowered):
            return label
    return None


def is_allowed_field(text: str) -> bool:
    lowered = text.lower()
    return any(field in lowered for field in ALLOWED_FIELDS)
